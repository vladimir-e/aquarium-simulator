import type { AmpEntry } from '../../simulation/livestock/amp.js';

const INDENT = '  ';

const key = (name: string): string => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`);

const quote = (text: string): string => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function literal(value: unknown, depth: number): string {
  if (typeof value === 'string') return quote(value);
  if (typeof value === 'number') return String(value);
  const inner = INDENT.repeat(depth + 1);
  const outer = INDENT.repeat(depth);
  if (Array.isArray(value)) {
    return `[\n${value.map((item) => `${inner}${literal(item, depth + 1)},\n`).join('')}${outer}]`;
  }
  const entries = Object.entries(value as Record<string, unknown>);
  if (entries.length === 0) return '{}';
  const fields = entries.map(([name, item]) => `${inner}${key(name)}: ${literal(item, depth + 1)},\n`);
  return `{\n${fields.join('')}${outer}}`;
}

export function renderEntry(entry: AmpEntry): string {
  return [
    `// Generated by \`npm run amp -- ${entry.entry}\` from data/amp/${entry.entry}.`,
    "import type { AmpEntry } from '../../amp.js';",
    '',
    `export const ${entry.entry}: AmpEntry = ${literal(entry, 0)};`,
    '',
  ].join('\n');
}
